"""Generate LaTeX macros/tables directly from canonical CSV outputs."""
from __future__ import annotations

from pathlib import Path
import numpy as np
import pandas as pd
from scipy.stats import wilcoxon

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"

budget = pd.read_csv(ROOT / "results" / "budget_curves" / "budget_curve_raw.csv")
family = pd.read_csv(ROOT / "results" / "family_replication" / "family_sampler_results.csv")
chains = pd.read_csv(ROOT / "results" / "family_replication" / "family_chain_results.csv")
structural = pd.read_csv(ROOT / "results" / "family_replication" / "family_structural_certificates.csv")

max_budget = int(budget.local_proposals_per_chain.max())
local_max = budget[(budget.method == "local") & (budget.local_proposals_per_chain == max_budget)].sort_values(["n", "graph_seed"]).reset_index(drop=True)
pt_max = budget[(budget.method == "parallel_tempering") & (budget.local_proposals_per_chain == max_budget)].sort_values(["n", "graph_seed"]).reset_index(drop=True)

macros = {
    "BudgetMax": f"{max_budget:,}",
    "BudgetMaxPower": "2^{18}",
    "BudgetLocalAll": f"{local_max.mean_row_tv.mean():.3f}",
    "BudgetLocalAllSE": f"{local_max.mean_row_tv.sem():.3f}",
    "BudgetPTAll": f"{pt_max.mean_row_tv.mean():.3f}",
    "BudgetPTAllSE": f"{pt_max.mean_row_tv.sem():.3f}",
    "BudgetPTLowerCount": str(int((pt_max.mean_row_tv.to_numpy() < local_max.mean_row_tv.to_numpy()).sum())),
    "BudgetAllCount": str(len(local_max)),
    "BudgetLocalPass": str(int((local_max.mean_row_tv < 0.1).sum())),
    "BudgetPTPass": str(int((pt_max.mean_row_tv < 0.1).sum())),
    "BudgetMaxPValue": f"{wilcoxon(local_max.mean_row_tv, pt_max.mean_row_tv).pvalue:.2e}",
    "FamilyGraphs": str(structural.shape[0]),
    "FamilyChains": str(chains.shape[0] // 2),
    "FamilyLocalTraversed": str(int(chains[chains.method == "local"].traverses_both_orientations.sum())),
    "FamilyJumpTraversed": str(int(chains[chains.method == "near_twin_jump"].traverses_both_orientations.sum())),
    "FamilyTotalChainsPerMethod": str(int((chains.method == "local").sum())),
    "FamilyLargeLocalTV": f"{family[(family.n >= 20) & (family.method == 'local')].opposing_start_row_tv.mean():.3f}",
    "FamilyLargeJumpTV": f"{family[(family.n >= 20) & (family.method == 'near_twin_jump')].opposing_start_row_tv.mean():.3f}",
    "FamilyLargeLocalTraverse": str(int(chains[(chains.n >= 20) & (chains.method == 'local')].traverses_both_orientations.sum())),
    "FamilyLargeJumpTraverse": str(int(chains[(chains.n >= 20) & (chains.method == 'near_twin_jump')].traverses_both_orientations.sum())),
    "FamilyLargeChains": str(int(((chains.n >= 20) & (chains.method == 'local')).sum())),
}
for n in [8, 9, 10]:
    word = {8: "Eight", 9: "Nine", 10: "Ten"}[n]
    a = local_max[local_max.n == n].reset_index(drop=True)
    b = pt_max[pt_max.n == n].reset_index(drop=True)
    macros[f"BudgetLocalN{word}"] = f"{a.mean_row_tv.mean():.3f}"
    macros[f"BudgetLocalN{word}SE"] = f"{a.mean_row_tv.sem():.3f}"
    macros[f"BudgetPTN{word}"] = f"{b.mean_row_tv.mean():.3f}"
    macros[f"BudgetPTN{word}SE"] = f"{b.mean_row_tv.sem():.3f}"
    macros[f"BudgetRatioN{word}"] = f"{a.mean_row_tv.mean()/b.mean_row_tv.mean():.1f}"
    macros[f"BudgetLocalPassN{word}"] = str(int((a.mean_row_tv < 0.1).sum()))
    macros[f"BudgetPTPassN{word}"] = str(int((b.mean_row_tv < 0.1).sum()))
    macros[f"BudgetCountN{word}"] = str(len(a))

with open(PAPER / "generated_results.tex", "w", encoding="utf-8") as f:
    f.write("% Auto-generated by code/generate_latex_results.py. Do not edit.\n")
    for name, value in macros.items():
        f.write(f"\\newcommand{{\\{name}}}{{{value}}}\n")

with open(PAPER / "generated_budget_table.tex", "w", encoding="utf-8") as f:
    f.write("% Auto-generated budget table rows.\n")
    for n in [8, 9, 10]:
        a = local_max[local_max.n == n]
        b = pt_max[pt_max.n == n]
        f.write(
            f"{n} & {len(a)} & ${a.mean_row_tv.mean():.3f}\\pm{a.mean_row_tv.sem():.3f}$ & "
            f"${b.mean_row_tv.mean():.3f}\\pm{b.mean_row_tv.sem():.3f}$ & "
            f"{int((a.mean_row_tv < .1).sum())}/{len(a)} & {int((b.mean_row_tv < .1).sum())}/{len(b)} \\\\\n"
        )

with open(PAPER / "generated_family_table.tex", "w", encoding="utf-8") as f:
    f.write("% Auto-generated family table rows.\n")
    for n in [16, 20, 24, 28]:
        l = family[(family.n == n) & (family.method == "local")]
        j = family[(family.n == n) & (family.method == "near_twin_jump")]
        d = structural[structural.n == n]
        lc = chains[(chains.n == n) & (chains.method == "local")]
        jc = chains[(chains.n == n) & (chains.method == "near_twin_jump")]
        f.write(
            f"{n} & ${d.delta_m.mean():.2f}\\pm{d.delta_m.sem():.2f}$ & "
            f"${l.opposing_start_row_tv.mean():.3f}\\pm{l.opposing_start_row_tv.sem():.3f}$ & "
            f"${j.opposing_start_row_tv.mean():.3f}\\pm{j.opposing_start_row_tv.sem():.3f}$ & "
            f"{int(lc.traverses_both_orientations.sum())}/{len(lc)} & "
            f"{int(jc.traverses_both_orientations.sum())}/{len(jc)} \\\\\n"
        )

print("generated LaTeX result files")
